CREATE SCHEMA IF NOT EXISTS qq_pay;
REVOKE ALL ON SCHEMA qq_pay FROM PUBLIC, anon, authenticated;
SET search_path TO qq_pay;
CREATE TABLE IF NOT EXISTS payments (id TEXT PRIMARY KEY, idem TEXT UNIQUE NOT NULL, amount BIGINT NOT NULL, currency TEXT NOT NULL, status TEXT NOT NULL); CREATE TABLE IF NOT EXISTS ledger (id TEXT PRIMARY KEY, payment TEXT NOT NULL, account TEXT NOT NULL, amount BIGINT NOT NULL); CREATE TABLE IF NOT EXISTS demo_limits (bucket BIGINT PRIMARY KEY, count INTEGER NOT NULL);
